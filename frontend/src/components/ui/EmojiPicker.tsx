const EmojiPicker: React.FC<EmojiPickerProps> = ({
  onEmojiSelect,
  isOpen,
  onClose,
  className
}) => {
  const [activeCategory, setActiveCategory] = useState('smileys');

  if (!isOpen) return null;

  return (
    <div className={cn(
      "absolute bottom-full right-0 mb-2 w-80 bg-background-secondary border border-border-default rounded-lg shadow-lg z-50",
      className
    )}>
      <div className="p-3">
        {/* Header */}
        <div className="flex items-center justify-between mb-3">
          <h3 className="text-sm font-medium text-foreground-primary">이모지 선택</h3>
          <button
            onClick={onClose}
            className="text-foreground-muted hover:text-foreground-primary transition-colors"
          >
            <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>

        {/* Category Tabs */}
        <div className="flex gap-1 mb-3 overflow-x-auto">
          {Object.entries(emojiCategories).map(([key, category]) => (
            <button
              key={key}
              onClick={() => setActiveCategory(key)}
              className={cn(
                "px-3 py-1 text-xs rounded-md whitespace-nowrap transition-colors",
                activeCategory === key
                  ? "bg-primary-500 text-foreground-primary"
                  : "text-foreground-muted hover:text-foreground-primary hover:bg-background-tertiary"
              )}
            >
              {category.name}
            </button>
          ))}
        </div>

        {/* Emoji Grid */}
        <div className="h-48 overflow-y-auto">
          <div className="grid grid-cols-8 gap-1">
            {emojiCategories[activeCategory as keyof typeof emojiCategories].emojis.map((emoji, index) => (
              <button
                key={index}
                onClick={() => {
                  onEmojiSelect(emoji);
                  onClose();
                }}
                className="w-8 h-8 flex items-center justify-center text-lg hover:bg-background-tertiary rounded transition-colors"
                title={emoji}
              >
                {emoji}
              </button>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
};

export default EmojiPicker;
